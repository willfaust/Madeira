#!/bin/bash
# Generate gnutls_symtab_ios.c — the static name->address table backing
# ios_gnutls_dlsym (see ios_gnutls_shim.h).
#
# Symbol set = every name Wine's three GnuTLS unixlibs resolve at
# runtime (LOAD_FUNCPTR/LOAD_FUNCPTR_OPT macros + direct quoted dlsym
# calls), intersected with what libgnutls.a actually defines. Optional
# symbols missing from our GnuTLS build simply don't get an entry;
# ios_gnutls_dlsym returns NULL and the unixlib's OPT path handles it.
#
# Entries reference symbols via __asm__ aliases, so no gnutls headers
# (and no prototype conflicts) are needed here at all.
set -e

BUILD_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$BUILD_DIR/../.." && pwd)"
WINE_SRC="$REPO_ROOT/wine"
# madeira-gnutls-lib-search: find the archive the app actually links.
#
# The toolchains/ prefix is the layout a from-source GnuTLS build produces, but
# the repository ships the built archive in app/Madeira/ instead. Looking only
# at the first one made the intersection below empty, which emits a table with
# no entries -- so nothing references libgnutls.a, the linker pulls in none of
# it, ios_gnutls_dlsym returns NULL for every name, and guest-side TLS silently
# does not work.
GNUTLS_LIB=""
for cand in "$REPO_ROOT/toolchains/gnutls-ios/lib/libgnutls.a" \
            "$REPO_ROOT/app/Madeira/libgnutls.a"; do
    if [ -f "$cand" ]; then GNUTLS_LIB="$cand"; break; fi
done
if [ -z "$GNUTLS_LIB" ]; then
    echo "ERROR: no libgnutls.a found. Looked in:" >&2
    echo "         $REPO_ROOT/toolchains/gnutls-ios/lib/" >&2
    echo "         $REPO_ROOT/app/Madeira/" >&2
    echo "       Generating an empty symbol table would disable guest TLS" >&2
    echo "       without saying so, so this stops instead." >&2
    exit 1
fi
echo "  gnutls symtab: using $GNUTLS_LIB"
OUT="$BUILD_DIR/gnutls_symtab_ios.c"

SOURCES=(
    "$WINE_SRC/dlls/bcrypt/gnutls.c"
    "$WINE_SRC/dlls/secur32/schannel_gnutls.c"
    "$WINE_SRC/dlls/crypt32/unixlib.c"
)

# 1. Names Wine wants: LOAD_FUNCPTR(name) / LOAD_FUNCPTR_OPT(name) /
#    dlsym(handle, "name")
wanted=$( {
    grep -hoE 'LOAD_FUNCPTR(_OPT)?\(\s*[A-Za-z0-9_]+' "${SOURCES[@]}" \
        | sed -E 's/LOAD_FUNCPTR(_OPT)?\(\s*//'
    grep -hoE 'dlsym\([^,]+,\s*"[A-Za-z0-9_]+"' "${SOURCES[@]}" \
        | sed -E 's/.*"([A-Za-z0-9_]+)".*/\1/'
} | grep -v '^f$' | sort -u )   # '^f$' = the LOAD_FUNCPTR(f) macro definition itself

# 2. Names libgnutls.a defines (defined symbols only, strip leading _)
available=$(nm -gU "$GNUTLS_LIB" 2>/dev/null | awk '{print $3}' | sed 's/^_//' | sort -u)

present=$(comm -12 <(echo "$wanted") <(echo "$available"))
missing=$(comm -23 <(echo "$wanted") <(echo "$available"))

{
    echo "/* Generated by gen_gnutls_symtab.sh — do not edit. */"
    echo "#include <string.h>"
    echo "#include <dlfcn.h>"
    echo
    n=0
    while read -r sym; do
        [ -z "$sym" ] && continue
        echo "extern char ios_gts_$n __asm__(\"_$sym\");"
        n=$((n+1))
    done <<< "$present"
    echo
    echo "static const struct { const char *name; void *addr; } ios_gnutls_symtab[] = {"
    n=0
    while read -r sym; do
        [ -z "$sym" ] && continue
        echo "    { \"$sym\", &ios_gts_$n },"
        n=$((n+1))
    done <<< "$present"
    echo "};"
    cat <<'EOF'

#define IOS_GNUTLS_MAGIC ((void *)&ios_gnutls_symtab)

void *ios_gnutls_dlopen(const char *name, int flags)
{
    if (name && strstr(name, "gnutls")) return IOS_GNUTLS_MAGIC;
    return dlopen(name, flags);
}

void *ios_gnutls_dlsym(void *handle, const char *name)
{
    unsigned int i;
    if (handle != IOS_GNUTLS_MAGIC) return dlsym(handle, name);
    for (i = 0; i < sizeof(ios_gnutls_symtab)/sizeof(ios_gnutls_symtab[0]); i++)
        if (!strcmp(ios_gnutls_symtab[i].name, name)) return ios_gnutls_symtab[i].addr;
    return 0;
}

int ios_gnutls_dlclose(void *handle)
{
    if (handle == IOS_GNUTLS_MAGIC) return 0;
    return dlclose(handle);
}
EOF
} > "$OUT"

count=$(echo "$present" | grep -c . || true)
echo "generated $OUT with $count symbols"
if [ -n "$missing" ]; then
    echo "NOT in libgnutls.a (OPT symbols get NULL; required ones will fail loudly at unixlib init):"
    echo "$missing" | sed 's/^/  /'
fi
